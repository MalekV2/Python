def sommes(a,b):
    """renvoie la somme de a+b qui sont les parametres
    parametre:a(int),b(int)
    valeurs de retour:somme de a et b en utilisant la recurrence de la fonction
    exemples:
    >>> sommes(1,2)
    3
    >>> sommes(2,2)
    4
    """

    if b==0:
        res=a
    elif b>0:
        res=sommes(a+1,b-1)
    else:
        res=sommes(a-1,b+1)
    return res
