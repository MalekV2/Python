def is_palindromic(s):
    """
    fonction permettant de reconaitre un palindrome
    parametre:
    -str, un mot
    valeurs de retours:
    - bool,True si c'est un palindrome
    False si non
    Exemples:
    >>> is_palindromic("biche")
    False
    >>> is_palindromic("radar")
    True
    >>> is_palindromic("kayak")
    True
    """
    n=len(s)
    if n<=1:
        res=True
    else:
        if s[0]==s[n-1]:
            res= is_palindromic(s[1:n-1])
        else:
            res=False
    return res













































